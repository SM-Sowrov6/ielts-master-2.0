"""Declarative base and shared model conventions (docs/DATABASE_SCHEMA.md §1).

Every module's ORM models inherit from `Base`. Constraint/index names follow one convention so
Alembic migrations are deterministic and reviewable.
"""

import uuid
from datetime import datetime

from sqlalchemy import DateTime, MetaData, Uuid, func
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

from app.shared.ids import new_id

# pk_<table>, fk_<table>_<column>_<referred_table>, uq_<table>_<columns>, ix_<column label>,
# ck_<table>_<name>. Check constraints must be given an explicit `name=`.
NAMING_CONVENTION: dict[str, str] = {
    "pk": "pk_%(table_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ix": "ix_%(column_0_label)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)
    type_annotation_map = {  # noqa: RUF012 — SQLAlchemy reads this class attribute
        uuid.UUID: Uuid(as_uuid=True),
        datetime: DateTime(timezone=True),  # always timestamptz
    }


class UUIDPrimaryKeyMixin:
    """`id uuid PRIMARY KEY`, UUIDv7 generated by the application (no server default)."""

    id: Mapped[uuid.UUID] = mapped_column(Uuid(as_uuid=True), primary_key=True, default=new_id)


class TimestampMixin:
    """`created_at` / `updated_at` as timestamptz NOT NULL DEFAULT now().

    `updated_at` is refreshed by the ORM on every UPDATE it emits (`onupdate`). Bulk Core
    `update()` statements must set it explicitly. Values use the database clock (transaction time).
    """

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now(), nullable=False
    )
